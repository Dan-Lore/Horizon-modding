#!/usr/bin/env python3
"""Pack mods/tfc into a combined .hmod.

Inlines tables/*.json into api/src/tables_embedded.rs so mixins/ has no JSON
(launcher rejects unexpected native source: mixins/**/*.json).
"""

from __future__ import annotations

import json
import re
import shutil
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "mods" / "tfc"
OUT = SRC / "dist" / "tfc.hmod"
REV = "fdc87aecdbd116bf1e08adcd062fcbaea8c2e2ca"
MIXINS = "5a64af938ec86b00d53d16a408aabc0038fb3e57"
HOOKS = 411

INCLUDE_RE = re.compile(
    r'include_str!\("\.\./\.\./tables/([^"]+)"\)'
)


def embed_tables(api_dir: Path) -> None:
    tables = SRC / "tables"
    consts: list[str] = []
    name_map: dict[str, str] = {}
    for path in sorted(tables.glob("*.json")):
        const = path.stem.upper() + "_JSON"
        name_map[path.name] = const
        raw = path.read_text(encoding="utf-8")
        consts.append(f"pub const {const}: &str = r#####\"{raw}\"#####;\n")
    embedded = api_dir / "src" / "tables_embedded.rs"
    embedded.write_text(
        "//! Auto-generated by tools/pack-tfc.py — do not edit.\n"
        + "".join(consts),
        encoding="utf-8",
        newline="\n",
    )
    # Patch every include_str to the embedded const; ensure mod declaration once.
    lib = api_dir / "src" / "lib.rs"
    lib_text = lib.read_text(encoding="utf-8")
    if "mod tables_embedded;" not in lib_text:
        lib.write_text(
            "mod tables_embedded;\n" + lib_text, encoding="utf-8", newline="\n"
        )
    for rs in (api_dir / "src").glob("*.rs"):
        if rs.name == "tables_embedded.rs":
            continue
        text = rs.read_text(encoding="utf-8")

        def repl(match: re.Match[str]) -> str:
            fname = match.group(1)
            const = name_map[fname]
            return f"crate::tables_embedded::{const}"

        new = INCLUDE_RE.sub(repl, text)
        if new != text:
            rs.write_text(new, encoding="utf-8", newline="\n")


def main() -> None:
    if not (SRC / "assets").is_dir() or not (SRC / "data").is_dir():
        raise SystemExit("missing generated content; run mods/tfc/tools/gen_content.py")
    stage = Path(tempfile.mkdtemp(prefix="tfc-pack-"))
    try:
        mixin = stage / "mixins" / "tfc"
        mixin.mkdir(parents=True)
        shutil.copy(SRC / "horizon-mod.toml", stage / "horizon-mod.toml")
        shutil.copytree(SRC / "assets", stage / "assets")
        shutil.copytree(SRC / "data", stage / "data")
        shutil.copy(SRC / "horizon-mixin.toml", mixin / "horizon-mixin.toml")
        shutil.copytree(
            SRC / "api",
            mixin / "api",
            ignore=shutil.ignore_patterns("target", ".horizon-cache"),
        )
        embed_tables(mixin / "api")
        for name in ("README.md", "NOTICE"):
            src = SRC / name
            if src.is_file():
                shutil.copy(src, mixin / name)
        # Read version from horizon-mod.toml
        version = "0.2.0"
        for line in (SRC / "horizon-mod.toml").read_text(encoding="utf-8").splitlines():
            if line.startswith("version"):
                version = line.split("=", 1)[1].strip().strip('"')
                break
        native = {
            "schema": 1,
            "id": "tfc",
            "version": version,
            "game": "26.3",
            "horizon": REV,
            "mixins": MIXINS,
            "hooks": HOOKS,
        }
        (stage / "horizon-native.json").write_text(json.dumps(native), encoding="utf-8")
        OUT.parent.mkdir(parents=True, exist_ok=True)
        if OUT.exists():
            OUT.unlink()
        with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as archive:
            for path in stage.rglob("*"):
                if path.is_file():
                    archive.write(path, path.relative_to(stage).as_posix())
        # sanity: no json under mixins
        with zipfile.ZipFile(OUT) as archive:
            bad = [
                n
                for n in archive.namelist()
                if n.startswith("mixins/") and n.endswith(".json")
            ]
            if bad:
                raise SystemExit(f"packed JSON under mixins: {bad[:5]}")
        print(f"{OUT} {OUT.stat().st_size}")
    finally:
        shutil.rmtree(stage)


if __name__ == "__main__":
    main()
